// Rendered is a demo track on disk with the analysis Rekordbox would find in it.
type Rendered struct {
	Track
	Path    string
	Length  float64 // seconds
	Beats   []float64
	BNum    []int
	Phrases []anlz.Phrase
}

// Render writes every demo track into dir as 24-bit AIFF, two at a time (a track needs about
// 1.5 GB while it renders).
func Render(dir string) ([]Rendered, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	out := make([]Rendered, len(Tracks))
	errs := make([]error, len(Tracks))
	sem := make(chan struct{}, 2)
	var wg sync.WaitGroup
	for i, t := range Tracks {
		wg.Add(1)
		go func() {
			defer wg.Done()
			sem <- struct{}{}
			defer func() { <-sem }()
			pcm := synth.Render(t.Song)
			path := filepath.Join(dir, t.File())
			if err := writeAIFF(path, t, pcm); err != nil {
				errs[i] = err
				return
			}
			out[i] = analyse(t, path, len(pcm)/2)
		}()
	}
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			return nil, err
		}
	}
	return out, nil
}

// analyse is the track's beat grid (from 0 s, 4/4) and its phrases: one per section, long
// sections split into 16-bar phrases, labelled as Rekordbox labels a high-mood track.
func analyse(t Track, path string, frames int) Rendered {
	s := t.Song
	length := float64(frames) / synth.SR
	nb := int(length * s.BPM / 60)
	r := Rendered{Track: t, Path: path, Length: length, Beats: make([]float64, nb), BNum: make([]int, nb)}
	for i := range nb {
		r.Beats[i] = float64(i) * 60 / s.BPM
		r.BNum[i] = i%4 + 1
	}
	l := s.Layout
	bar := 0
	sections := []struct {
		label string
		bars  int
	}{{"Intro", l.Intro}, {"Up", l.Groove}, {"Chorus", l.Main}, {"Down", l.Break}, {"Chorus", l.Drop}, {"Outro", l.Outro}}
	for _, sec := range sections {
		for b := 0; b < sec.bars; b += 16 {
			r.Phrases = append(r.Phrases, anlz.Phrase{Beat: (bar+b)*4 + 1, Label: sec.label})
		}
		bar += sec.bars
	}
	return r
}

// writeAIFF encodes interleaved float32 stereo as 24-bit AIFF with ID3 tags (ffmpeg).
func writeAIFF(path string, t Track, pcm []float32) error {
	cmd := exec.Command("ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", fmt.Sprint(synth.SR), "-ac", "2",
		"-i", "-", "-c:a", "pcm_s24be", "-write_id3v2", "1", "-fflags", "+bitexact",
		"-metadata", "title="+t.Title, "-metadata", "artist=auto-dj demo", "-metadata", "album="+Playlist,
		"-metadata", "genre=Deep House", "-metadata", fmt.Sprintf("track=%d/%d", t.No, len(Tracks)),
		"-metadata", "comment=Generated by auto-dj (CC0)", path)
	in, err := cmd.StdinPipe()
	if err != nil {
		return err
	}
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("ffmpeg: %w", err)
	}
	w := bufio.NewWriterSize(in, 1<<20)
	var buf [4]byte
	for _, v := range pcm {
		binary.LittleEndian.PutUint32(buf[:], math.Float32bits(v))
		if _, err := w.Write(buf[:]); err != nil {
			break
		}
	}
	_ = w.Flush()
	_ = in.Close()
	if err := cmd.Wait(); err != nil {
		return fmt.Errorf("ffmpeg writing %s: %w: %s", path, err, strings.TrimSpace(stderr.String()))
	}
	return nil
}
